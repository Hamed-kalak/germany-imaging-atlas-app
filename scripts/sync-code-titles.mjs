/**
 * Regenerate src/data/codeDescriptions.ts from the Article's verified rubrics.
 *
 * The map used to come from scripts/enrich-codes.mjs, which looked codes up in
 * ICD-10-CM 2026 over an MCP server.  That is the wrong classification for this
 * data -- the DRG statistics code in ICD-10-GM, the German modification of WHO
 * ICD-10 -- and it made the dashboard name 153 of the 624 codes differently
 * from the paper: US spelling (leukemia, esophagus, behavior) but also real
 * rubric differences, e.g. A15 "Respiratory tuberculosis" against WHO's
 * "Respiratory tuberculosis, bacteriologically and histologically confirmed".
 *
 * The source of truth is now research/code/analysis/output/icd_titles.json,
 * built and cross-checked by analysis/icd_titles.py against three sources.
 *
 *   node scripts/sync-code-titles.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = join(__dirname, '..', '..', '..', 'research', 'code', 'analysis',
                 'output', 'icd_titles.json');
const OUT = join(__dirname, '..', 'src', 'data', 'codeDescriptions.ts');

const titles = JSON.parse(readFileSync(SRC, 'utf8'));
const codes = Object.keys(titles).sort();

const body = codes
  .map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify(titles[c])},`)
  .join('\n');

writeFileSync(OUT, `/**
 * ICD-10 three-character rubrics -- the same ones the Article prints in
 * appendix tables S1 and S3, so the dashboard and the paper name every code
 * identically.
 *
 * Generated by scripts/sync-code-titles.mjs from
 * research/code/analysis/output/icd_titles.json.  Do not edit by hand; run
 * analysis/icd_titles.py and then this script.
 *
 * Source: WHO ICD-10 (2019), which ICD-10-GM derives from, with five rubrics
 * (A09, D70, G81, G82, J80) following ICD-10-GM where it is materially broader.
 */
export const CODE_DESCRIPTIONS: Record<string, string> = {
${body}
};
`, 'utf8');

console.log(`codeDescriptions.ts: ${codes.length} rubrics from the Article`);
